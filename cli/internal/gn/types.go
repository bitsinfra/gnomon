package gn

import (
	"context"
	"fmt"
	"sort"
	"strings"

	"github.com/jackc/pgx/v5"
)

func init() {
	register(&Command{Name: "types", Usage: "types --lang ts|py [--schema s]", Summary: "generate a type per tracked table (rows, keys) for the SDKs", Run: typesCmd})
}

type col struct {
	name, typ            string
	nullable, key, array bool
}

// typesCmd writes one type per tracked table from the catalog: its row type and
// its key, and a Database map the SDKs' generics take.
func typesCmd(ctx context.Context, o *Options, args []string) error {
	fs := flags("types")
	lang := fs.String("lang", "ts", "ts or py")
	schema := fs.String("schema", "", "only this schema")
	if _, err := parse(fs, args); err != nil {
		return err
	}
	return withConn(ctx, o, func(c *pgx.Conn) error {
		res, err := Query(ctx, c, `select t.nsp, t.relname, a.attname, format_type(a.atttypid, a.atttypmod) as typ,
		        not a.attnotnull as nullable, a.attname = any(t.key_cols) as key, a.attnum,
		        coalesce((select e.typname from pg_type ty join pg_type e on e.oid = ty.typelem where ty.oid = a.atttypid and ty.typcategory = 'A'), '') as elem,
		        (select ty.typname from pg_type ty where ty.oid = a.atttypid) as base
		   from gnomon.tracked t join pg_attribute a on a.attrelid = t.rel and a.attnum > 0 and not a.attisdropped
		  where $1 = '' or t.nsp = $1 order by t.nsp, t.relname, a.attnum`, *schema)
		if err != nil {
			return err
		}
		tables := map[string][]col{}
		var order []string
		for _, m := range res.Maps {
			k := fmt.Sprintf("%v.%v", m["nsp"], m["relname"])
			if _, ok := tables[k]; !ok {
				order = append(order, k)
			}
			base := fmt.Sprint(m["base"])
			arr := fmt.Sprint(m["elem"]) != ""
			if arr {
				base = fmt.Sprint(m["elem"])
			}
			tables[k] = append(tables[k], col{name: fmt.Sprint(m["attname"]), typ: base, nullable: m["nullable"] == true, key: m["key"] == true, array: arr})
		}
		sort.Strings(order)
		if *lang == "py" {
			fmt.Fprint(o.Out, typesPy(order, tables))
		} else {
			fmt.Fprint(o.Out, typesTS(order, tables))
		}
		return nil
	})
}

func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' || r == '.' || r == '-' {
			up = true
			continue
		}
		if up {
			b.WriteString(strings.ToUpper(string(r)))
			up = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func tsType(c col) string {
	t := "unknown"
	switch c.typ {
	case "int2", "int4", "float4", "float8", "oid":
		t = "number"
	case "int8":
		t = "bigint | number"
	case "numeric", "money":
		t = "string | number"
	case "bool":
		t = "boolean"
	case "json", "jsonb":
		t = "unknown"
	case "text", "varchar", "bpchar", "name", "uuid", "citext", "date", "timestamp", "timestamptz", "time", "timetz", "interval", "inet", "cidr", "bytea":
		t = "string"
	}
	if c.array {
		t = "Array<" + t + ">"
	}
	if c.nullable {
		t += " | null"
	}
	return t
}

func typesTS(order []string, tables map[string][]col) string {
	var b strings.Builder
	b.WriteString("// Generated by `gnomon types --lang ts`: one row type per tracked table, its key, and the\n// Database map @bitsinfra/gnomon's generics take. Do not edit; generate again after schema changes.\n\n")
	for _, t := range order {
		n := pascal(strings.TrimPrefix(t, "public."))
		fmt.Fprintf(&b, "export interface %sRow {\n", n)
		var keys []string
		for _, c := range tables[t] {
			fmt.Fprintf(&b, "  %q: %s;\n", c.name, tsType(c))
			if c.key {
				keys = append(keys, fmt.Sprintf("%q: %s", c.name, tsType(c)))
			}
		}
		fmt.Fprintf(&b, "}\nexport type %sKey = { %s };\n\n", n, strings.Join(keys, "; "))
	}
	b.WriteString("export interface Database {\n")
	for _, t := range order {
		n := pascal(strings.TrimPrefix(t, "public."))
		fmt.Fprintf(&b, "  %q: { row: %sRow; key: %sKey };\n", t, n, n)
	}
	b.WriteString("}\n")
	return b.String()
}

func pyType(c col) string {
	t := "Any"
	switch c.typ {
	case "int2", "int4", "int8", "oid":
		t = "int"
	case "float4", "float8":
		t = "float"
	case "numeric", "money":
		t = "Decimal"
	case "bool":
		t = "bool"
	case "text", "varchar", "bpchar", "name", "uuid", "citext", "date", "timestamp", "timestamptz", "time", "timetz", "interval", "inet", "cidr", "bytea":
		t = "str"
	}
	if c.array {
		t = "list[" + t + "]"
	}
	if c.nullable {
		t = "Optional[" + t + "]"
	}
	return t
}

func typesPy(order []string, tables map[string][]col) string {
	var b strings.Builder
	b.WriteString("\"\"\"Generated by `gnomon types --lang py`: a TypedDict per tracked table and its key. Do not edit.\"\"\"\nfrom __future__ import annotations\n\nfrom decimal import Decimal\nfrom typing import Any, Optional, TypedDict\n\n")
	for _, t := range order {
		n := pascal(strings.TrimPrefix(t, "public."))
		fmt.Fprintf(&b, "\nclass %sRow(TypedDict):\n", n)
		var keys []col
		for _, c := range tables[t] {
			fmt.Fprintf(&b, "    %s: %s\n", c.name, pyType(c))
			if c.key {
				keys = append(keys, c)
			}
		}
		fmt.Fprintf(&b, "\n\nclass %sKey(TypedDict):\n", n)
		for _, c := range keys {
			fmt.Fprintf(&b, "    %s: %s\n", c.name, pyType(c))
		}
		b.WriteString("\n")
	}
	b.WriteString("\nTABLES = {\n")
	for _, t := range order {
		n := pascal(strings.TrimPrefix(t, "public."))
		fmt.Fprintf(&b, "    %q: (%sRow, %sKey),\n", t, n, n)
	}
	b.WriteString("}\n")
	return b.String()
}
