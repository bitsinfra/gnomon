func specDir() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "..", "sdk", "spec")
}

// The Go port of the snapshot rules passes the SDKs' golden files.
func TestNormalizeDiffGolden(t *testing.T) {
	files, _ := filepath.Glob(filepath.Join(specDir(), "snapshot", "*.json"))
	for _, f := range files {
		b, _ := os.ReadFile(f)
		var g struct {
			Ignore      []string     `json:"ignore"`
			ForeignKeys []ForeignKey `json:"foreign_keys"`
			Diff        []DiffRow    `json:"diff"`
			Expected    []string     `json:"expected"`
		}
		d := json.NewDecoder(strings.NewReader(string(b)))
		d.UseNumber()
		if err := d.Decode(&g); err != nil {
			t.Fatal(err)
		}
		got := NormalizeDiff(g.Diff, g.Ignore, g.ForeignKeys)
		if strings.Join(got, "\n") != strings.Join(g.Expected, "\n") {
			t.Fatalf("%s:\n got %q\nwant %q", f, got, g.Expected)
		}
	}
}

// gnomon eval: trials fork at the base, the agent writes its branch, the diff is scored.
func TestEval(t *testing.T) {
	dsn := testdb.New(t, t.Name())
	testdb.Exec(t, dsn,
		"create table item (id int generated by default as identity primary key, name text not null, qty int not null default 0)",
		"insert into item (name) values ('a'), ('b')",
		"select gnomon.track('item')",
		"select gnomon.create_tag('eval-base')")
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "want.txt"), []byte("public.item <item:1> update qty: 0 -> 5\n"), 0o644)
	spec := `{"name": "restock", "base": "tag:eval-base", "task": "set qty of a to 5", "trials": 2,
	  "command": ["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-c", "update item set qty = 5 where name = 'a'"],
	  "expect": {"diff": "want.txt", "unchanged": [], "max_rows": 1}}`
	os.WriteFile(filepath.Join(dir, "spec.json"), []byte(spec), 0o644)
	var out strings.Builder
	o := &Options{DSN: dsn, Out: &out}
	// psql takes the branch from PGOPTIONS and the database from the libpq environment
	cfg := strings.Fields(dsn)
	for _, kv := range cfg {
		k, v, _ := strings.Cut(kv, "=")
		os.Setenv(map[string]string{"host": "PGHOST", "port": "PGPORT", "user": "PGUSER", "dbname": "PGDATABASE"}[k], v)
	}
	if err := evalCmd(context.Background(), o, []string{filepath.Join(dir, "spec.json")}); err != nil {
		t.Fatalf("%v\n%s", err, out.String())
	}
	if !strings.Contains(out.String(), `"passed":2`) {
		t.Fatalf("eval: %s", out.String())
	}
	if got := testdb.Scalar(t, dsn, "select qty from item where name = 'a'"); got != "0" {
		t.Fatalf("main changed: %s", got)
	}
}
