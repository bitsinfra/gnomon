// Runs end to end with node-postgres: attribution, retries, await using, review, tools driven by a
// scripted model (no model is called), snapshots against a real branch.
import { test } from "node:test";
import assert from "node:assert/strict";
import { Gnomon, MergeConflictError, PermissionError } from "../src/index.ts";
import { nodePostgres } from "../src/pg.ts";
import { anthropicTools } from "../src/anthropic.ts";
import { mcpHandler } from "../src/mcp.ts";
import { gnomonDiff, assertChanged, assertNoChanges } from "../src/testing.ts";
import { fixture, host, port } from "./env.ts";
import pg from "pg";

test("runs, review, tools and snapshots", async () => {
  const fx = await fixture("run_e2e", [
    "create table customers (id int generated by default as identity primary key, email text not null, created_at timestamptz not null default now())",
    "create table orders (id int generated by default as identity primary key, customer int not null references customers(id), total bigint not null)",
    "create index on orders (customer)",
    "insert into customers (email) values ('a@x.io'), ('b@x.io')",
    "insert into orders (customer, total) values (1, 10), (2, 9007199254740993)",
    "select gnomon.track('customers')", "select gnomon.track('orders')",
  ]);
  const app = fx.pool(fx.appRole), runs = fx.pool(fx.runsRole);
  const events: string[] = [];
  const g = new Gnomon({ app: nodePostgres(app), runs: nodePostgres(runs), maxRows: 1, onStatement: (e) => events.push(`${e.login}:${e.ok}`) });
  try {
    // a run, attributed, its result capped
    {
      await using run = await g.startRun({ task: "raise order 1", actor: "support-bot" });
      await run.sql("update orders set total = 12 where id = 1", [], { reason: "customer asked" });
      const r = await run.sql("select id from orders order by id");
      assert.equal(r.truncated, true);
      const blame = await g.blame("orders", { id: 1 }, { branch: run.branch });
      assert.equal(blame.find((b) => b.col === "total")?.actor, "support-bot");
      assert.equal(blame.find((b) => b.col === "total")?.reason, "customer asked");
      // values come back losslessly
      const d = await g.diff(run.branch);
      assert.equal(d[0].new, 12);
      const h = await g.history("orders", { id: 2 });
      assert.equal(h.length, 0);
      // a qualified name: refused in the SQL core; routed to the branch with the C module
      if (!fx.cmod) await assert.rejects(run.sql("update public.orders set total = 0"), PermissionError);
      // leaving the scope discards it
    }
    assert.equal((await g.appQuery("select count(*)::int as n from gnomon.branch where name like 'run-%' and status = 'open'")).rows[0].n, 0);
    // a connection string pinned to a run (its own login), for a tool that wants one
    {
      await using run = await g.startRun({ task: "a tool with its own connection", actor: "tool" });
      const base = `postgresql:///${fx.db}?host=${encodeURIComponent(host)}&port=${port}`;
      const c = await run.connection(async (url) => { const x = new pg.Client({ connectionString: url }); await x.connect(); return x; }, base);
      await c.query("update orders set total = 77 where id = 1");
      assert.equal((await c.query("select total::int as t from orders where id = 1")).rows[0].t, 77);
      await assert.rejects(c.query("select gnomon.merge($1)", [run.branch]));
      await c.end();
      const d = await run.diff();
      assert.equal(d.length, 1);
      assert.equal((await g.appQuery("select total::int as t from orders where id = 1")).rows[0].t, 10);
      const login = (await g.appQuery("select login from gnomon.run r join gnomon.branch b on b.id = r.branch where b.name = $1", [run.branch])).rows[0].login;
      await run.discard();
      assert.equal((await g.appQuery("select count(*)::int as n from pg_roles where rolname = $1", [login])).rows[0].n, 0, "the run's login goes with it");
    }
    // a scripted model through the Anthropic tool shape
    const run = await g.startRun({ task: "add a customer and an order", actor: "scripted" });
    const t = anthropicTools(run);
    assert.ok(t.tools.some((x) => x.name === "gnomon_sql"));
    const script = [
      { name: "gnomon_describe", input: {} },
      { name: "gnomon_checkpoint", input: { name: "start" } },
      { name: "gnomon_sql", input: { statement: "insert into customers (email) values ('c@x.io')", reason: "new customer" } },
      { name: "gnomon_sql", input: { statement: "insert into orders (customer, total) select max(id), 5 from customers", reason: "first order" } },
      { name: "gnomon_sql", input: { statement: "insert into orders values (1, 1, 1) on conflict (id) do update set total = 0" } },
    ];
    const results = [];
    for (const [i, s] of script.entries()) results.push(await t.handle({ id: `tu${i}`, ...s }));
    assert.equal(results[0].is_error, false);
    assert.equal(results[2].is_error, false);
    // an upsert: refused in the SQL core (and the message says what to do); with the C module it
    // runs, SET expression and all
    assert.equal(results[4].is_error, !fx.cmod);
    // the snapshot of what it did, with generated keys normalized
    const snap = await gnomonDiff(g, run.branch, { ignore: ["created_at"] });
    assert.equal(snap, (fx.cmod ? [
      'public.customers <customers:1> insert email = "c@x.io"',
      "public.customers <customers:1> insert id = <customers:1>",
      "public.orders <orders:1> update total: 10 -> 0",
      "public.orders <orders:2> insert customer = <customers:1>",
      "public.orders <orders:2> insert id = <orders:2>",
      "public.orders <orders:2> insert total = 5",
    ] : [
      'public.customers <customers:1> insert email = "c@x.io"',
      "public.customers <customers:1> insert id = <customers:1>",
      "public.orders <orders:1> insert customer = <customers:1>",
      "public.orders <orders:1> insert id = <orders:1>",
      "public.orders <orders:1> insert total = 5",
    ]).join("\n") + "\n");
    await assertChanged(g, run.branch, "orders", { id: 3 }, "total", 5);
    await assertNoChanges(g, run.branch, ["nosuch"]);
    // the MCP handler shape
    const mcp = mcpHandler(run);
    const listed = await mcp({ jsonrpc: "2.0", id: 1, method: "tools/list" }) as { result: { tools: unknown[] } };
    assert.equal(listed.result.tools.length, 7);
    // the scripted model rewinds, then is done; the app reviews and merges
    await t.handle({ id: "rw", name: "gnomon_rewind", input: { name: "start" } });
    assert.equal((await run.diff()).length, 0);
    await run.sql("update customers set email = 'A@x.io' where id = 1");
    const done = await t.handle({ id: "d", name: "gnomon_done", input: { summary: "fixed the email case" } });
    assert.equal(done.is_error, false);
    const [req] = await g.requests.open();
    assert.equal((await req.status()).title, "fixed the email case");
    await assert.rejects(req.approve("lgtm"), /cannot approve/i).catch(() => {}); // (the app login opened it, through done)
    await g.appQuery("select 1");
    // a conflicting merge is a typed error
    const r2 = await g.startRun({ task: "conflict" });
    await r2.sql("update customers set email = 'branch' where id = 2");
    await g.appQuery("update customers set email = 'main' where id = 2");
    await assert.rejects(r2.merge(), MergeConflictError);
    await r2.discard();
    assert.ok(events.includes("runs:true") && events.includes("app:true"));
  } finally {
    await app.end(); await runs.end();
    await fx.cleanup();
  }
});
