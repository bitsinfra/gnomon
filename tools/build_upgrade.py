"""Build a gnomon upgrade script: prologue, migrations, the new version's code, epilogue.

  python3 tools/build_upgrade.py NEW_FULL.sql FROM TO [--plain] > gnomon--FROM--TO.sql

The new version's code is every statement of its full install script that can be run again on an
existing installation: functions, procedures, views (as CREATE OR REPLACE), casts, grants,
revokes, comments, DO blocks (roles, event triggers, dump registration) and the default settings
(upserted). Tables, types, sequences, indexes and schemas belong to the migrations in src/upgrade.
"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from sqlsplit import split, head

new_sql, frm, to = sys.argv[1], sys.argv[2], sys.argv[3]
plain = '--plain' in sys.argv
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
up = os.path.join(root, 'src', 'upgrade')

src = open(new_sql).read()
src = re.sub(r'^\\echo .*$', '', src, flags=re.M)

KEEP = ('create function', 'create or replace function', 'create procedure', 'create or replace procedure',
        'create view', 'create or replace view', 'create cast', 'grant ', 'revoke ', 'comment on ', 'do ',
        'alter function', 'alter procedure', 'alter view')
SKIP = ('create schema', 'create table', 'create unlogged table', 'create index', 'create unique index',
        'create sequence', 'create type', 'insert into gnomon.branch', 'begin', 'commit')
def read(p):
    # a migration may take a file of src/sql whole: `-- @include src/sql/<file>` (its CREATE
    # statements are written IF NOT EXISTS, so they run on an installation that has them)
    out = []
    for line in open(p).read().splitlines():
        m = re.match(r'^-- @include (\S+)$', line)
        out.append(open(os.path.join(root, m.group(1))).read().rstrip() if m else line)
    return '\n'.join(out).rstrip() + '\n'

def norm(st):
    return re.sub(r'\s+', ' ', st.strip().rstrip(';')).lower()

# statements a migration already runs (catalog changes of src/sql files the migrations include
# whole): skipped in the code section rather than refused
migrated = {norm(st) for m in sorted(glob.glob(os.path.join(up, '[0-9]*.sql'))) for st in split(read(m)) if head(st)}

code = []
for st in split(src):
    h = head(st)
    if not h:
        continue
    if h.startswith('insert into gnomon.setting_default'):
        code.append(st.rstrip().rstrip(';') + '\n  on conflict (name) do update set value = excluded.value, doc = excluded.doc;')
    elif h.startswith(('create view', 'create function', 'create procedure')):
        code.append(re.sub(r'(?i)\bcreate\s+(view|function|procedure)\b', r'create or replace \1', st, count=1))
    elif h.startswith(KEEP):
        code.append(st)
    elif h.startswith(SKIP) or norm(st) in migrated:
        continue
    else:
        raise SystemExit(f'build_upgrade: do not know how to carry this statement into an upgrade:\n{h[:200]}')


out = [f'-- gnomon {frm} -> {to}, generated by tools/build_upgrade.py from src/upgrade and the {to} install script.\n',
       f'-- Do not edit: change src/upgrade or src/sql and build again.\n']
if not plain:
    out.append('\\echo Use "ALTER EXTENSION gnomon UPDATE" to load this file. \\quit\n')
else:
    out.append('begin;\n')
out.append('\n-- 1. prologue\n' + read(os.path.join(up, '_prologue.sql')))
for m in sorted(glob.glob(os.path.join(up, '[0-9]*.sql'))):
    out.append(f'\n-- 2. migration {os.path.basename(m)}\n' + read(m))
out.append(f'\n-- 3. the {to} code\n')
out.extend(s.strip() + '\n' for s in code)
out.append('\n-- 4. epilogue\n' + read(os.path.join(up, '_epilogue_plain.sql' if plain else '_epilogue.sql')))
if plain:
    out.append("update gnomon.setting_default set value = 'plain' where name = 'install_form';\ncommit;\n")
sys.stdout.write(''.join(out))
