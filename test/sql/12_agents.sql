-- A role is a branch, agents, runs and read isolation, quotas,
-- the kill switch and run record, expiry, and the one-document functions.
\set ON_ERROR_STOP on
select current_database() as db \gset
drop role if exists gnomon_agent_bot; drop role if exists gnomon_agent_spy; drop role if exists gt_app; drop role if exists gt_runs;
create table products (id int generated by default as identity primary key, name text not null, price int not null);
create table orders (id bigserial primary key, product int not null references products(id), qty int not null);
insert into products (name, price) select 'p' || g, g * 10 from generate_series(1, 5) g;
insert into orders (product, qty) values (1, 1), (2, 2);
select gnomon.track('products'); select gnomon.track('orders');
select gnomon.add_check('no_free', 'select * from products where price <= 0');

-------------------------------------------------------------------------------
-- agent create: a login on its own branch, nothing on the base tables
select gnomon.agent_create('bot') as created \gset
select (:'created'::jsonb) ->> 'role' as bot_role, (:'created'::jsonb) ->> 'token' as bot_token \gset
select t.eq(:'bot_role'::text, 'gnomon_agent_bot', 'agent role name');
select t.eq((select b.name from gnomon.assignment a join gnomon.branch b on b.id = a.branch where a.role = 'gnomon_agent_bot'), 'bot/1', 'assigned to its branch');
select t.ok(exists (select 1 from pg_db_role_setting s join pg_roles r on r.oid = s.setrole
                     where r.rolname = 'gnomon_agent_bot' and 'gnomon.branch=bot/1' = any(s.setconfig)), 'role default names the branch');
select t.ok(not has_table_privilege('gnomon_agent_bot', 'products', 'SELECT'), 'no grant on the base table');

-- a plain connection as the agent starts on its branch
\c - gnomon_agent_bot
select t.eq(gnomon.current_branch(), 'bot/1', 'a plain connection starts on the branch');
insert into products (name, price) values ('new', 99);           -- an identity column: confine granted the sequence
update products set price = 11 where id = 1;
select t.eq((select price from products where id = 1), 11, 'the agent reads its write');
-- (the C module routes qualified names to the branch; the SQL core refuses them for a role with no grant)
select coalesce(current_setting('gnomon.c_module', true), '') = 'on' as cmod \gset
\if :cmod
select t.eq((select price from public.products where id = 1), 11, 'with the C module a qualified read reads the branch');
\else
select t.fails($$select * from public.products$$, '42501', 'a qualified read of main fails loudly');
select t.fails($$update public.products set price = 0 where id = 2$$, '42501', 'a qualified write of main fails');
\endif
select t.fails($$select gnomon.merge('bot/1')$$, '42501', 'the agent cannot merge into main');
select t.ok((select count(*) from gnomon.diff('bot/1')) >= 2, 'the agent diffs its own branch without a base-table grant');
select t.ok((select bool_and(passed) from gnomon.run_checks('bot/1')), 'the agent runs the checks');
select t.eq((select op from gnomon.history('products', '1', 'bot/1') order by vkey desc limit 1), 'update', 'and reads its row history');
select t.eq((gnomon.status() ->> 'routed')::bool, true, 'status: routed');
select t.eq(gnomon.status() ->> 'branch', 'bot/1', 'status: on its branch');
select t.eq((gnomon.describe() -> 'session' ->> 'can_write')::bool, true, 'describe: may write');
select t.ok(gnomon.describe() -> 'tables' @> '[{"name": "products", "tracked": true}]', 'describe lists the tracked table');
select gnomon.done('raised a price') as cr \gset
select t.ok(:cr > 0, 'done() opens a change request');
-- the agent leaving its branch reaches nothing on main
select gnomon.use('main');
select t.fails($$update products set price = 0 where id = 2$$, '42501', 'reset to main, still no write');
\c - postgres
select t.eq((select price from products where id = 1), 10, 'main is unchanged');
select t.eq((select count(*) from gnomon.diff('bot/1') where tbl = 'products'::regclass), 2::bigint, 'the reviewer sees the agent''s two changes');
select t.eq((select opened_by::text from gnomon.change_request where id = :cr), 'gnomon_agent_bot', 'the change request is the agent''s');
select t.ok(gnomon.change_request_status(:cr) ->> 'title' = 'raised a price', 'change request status document');

-- agent next: a fresh branch per task
select t.eq(gnomon.agent_next('bot'), 'bot/2', 'next branch');
select t.ok(exists (select 1 from pg_db_role_setting s join pg_roles r on r.oid = s.setrole
                     where r.rolname = 'gnomon_agent_bot' and 'gnomon.branch=bot/2' = any(s.setconfig)), 'the role moves to it');

-------------------------------------------------------------------------------
-- read isolation: a second agent cannot read the first one's branch
select gnomon.agent_create('spy') \gset
\c - gnomon_agent_spy
select t.fails($$select gnomon.use('bot/1')$$, '42501', 'another agent''s branch is not readable');
select t.fails($$select * from gnomon.history('products', '1', 'bot/1')$$, '42501', 'nor its history');
select t.eq(gnomon.explain_error('42501', 'permission denied for table products') like '%confined%', true, 'explain_error for a confined role');
\c - postgres

-------------------------------------------------------------------------------
-- runs: an application login and a shared runs login, no superuser
create role gt_app login; create role gt_runs login;
grant gnomon_runner, gnomon_merger to gt_app;
grant select, insert, update, delete on products, orders to gt_app;
grant usage on all sequences in schema public to gt_app;
select gnomon.confine('gt_runs', array[]::text[], false);
select gnomon.set('runs_role', 'gt_runs');
\c - gt_app
select gnomon.run_start('refund order', 'support-bot') as run1 \gset
select gnomon.run_start('other task', 'support-bot') as run2 \gset
\c - gt_runs
begin;
select gnomon.begin(:'run1');
select gnomon.note('support-bot', 'refund', '{"run": "r1"}');
update products set price = 1 where id = 3;
commit;
begin;
select gnomon.begin(:'run2');
update products set price = 2 where id = 4;
commit;
begin;
select gnomon.begin(:'run2');
select t.fails(format('select gnomon.use(%L)', :'run1'), '42501', 'a run cannot read another run''s branch');
rollback;
\c - gt_app
select t.eq((select (gnomon.run_summary(:'run1') -> 'changes' ->> 'rows')::int), 1, 'run summary counts the change');
select t.ok((gnomon.run_summary(:'run1') -> 'checks' ->> 'passed')::bool, 'and the checks pass (run as the app login)');
select gnomon.merge(:'run1') as m1 \gset
select t.eq((select price from products where id = 3), 1, 'the app login merges a run');
select t.eq((select actor from gnomon.history('products', '3') order by vkey desc limit 1) is null, true, 'merged versions are the merger''s');
select gnomon.undo_merge(:m1);
select t.eq((select price from products where id = 3), 30, 'and undoes the merge as a non-superuser');
select gnomon.allow('gt_runs', :'run2', false);
select gnomon.run_end(:'run2');
select t.ok(not exists (select 1 from gnomon.branch where name = :'run2' and status = 'open'), 'run_end discards the branch');
\c - postgres

-------------------------------------------------------------------------------
-- quotas: open branches per role, rows per branch (marked by the heartbeat's pass)
select gnomon.set_quota('role', 'gnomon_agent_spy', max_branches => 1);   -- (its first branch was made by the admin)
\c - gnomon_agent_spy
select gnomon.create_branch('spy-child', 'spy/1');
select t.fails($$select gnomon.create_branch('spy-child-2', 'spy/1')$$, '53400', 'open branches over the role''s quota');
\c - postgres
select gnomon.set_quota('branch', 'spy/1', max_rows => 1);
\c - gnomon_agent_spy
update products set price = 7 where id = 1;
update products set price = 7 where id = 2;
\c - postgres
select t.eq(gnomon.check_quotas(), 1, 'the heartbeat marks one branch over quota');
\c - gnomon_agent_spy
select t.fails($$update products set price = 8 where id = 3$$, '53400', 'a branch over quota refuses writes');
select t.ok(gnomon.status() -> 'problems' ? (select e from jsonb_array_elements_text(gnomon.status() -> 'problems') e where e like 'over quota%' limit 1), 'status says so');
\c - postgres
select gnomon.set_quota('branch', 'spy/1');
select t.eq(gnomon.check_quotas(), 0, 'cleared when the quota goes');

-------------------------------------------------------------------------------
-- the run record: hash-chained, insert-only
\c - gnomon_agent_bot
select gnomon.record_call('run-a', 'query', '{"sql": "select 1"}', 'bot/2', gnomon.coordinate_text(), null, 1, 'abc');
select gnomon.record_call('run-a', 'query', '{"sql": "select 2"}', 'bot/2', gnomon.coordinate_text(), null, 1, 'def');
select t.fails($$insert into gnomon.agent_call(run, seq, tool, hash) values ('run-a', 9, 'x', '\x00')$$, '42501', 'the agent cannot write the record directly');
\c - postgres
select t.ok((select bool_and(ok) and count(*) = 2 from gnomon.verify_run('run-a')), 'the chain verifies');
update gnomon.agent_call set args = '{"sql": "drop table x"}' where run = 'run-a' and seq = 1;
select t.ok(not (select bool_and(ok) from gnomon.verify_run('run-a')), 'tampering breaks it');
select t.eq((select count(*) from gnomon.agent_call where run = 'run-a' and agent = 'bot'), 2::bigint, 'calls carry the agent');

-- token lookup is for gnomon's server
select t.eq((select name from gnomon.agent_auth(:'bot_token')), 'bot', 'a token maps to its agent');
\c - gnomon_agent_spy
select t.fails(format('select * from gnomon.agent_auth(%L)', :'bot_token'), '42501', 'an agent cannot look tokens up');
\c - postgres

-------------------------------------------------------------------------------
-- the kill switch: undo the merges of the agent's branches
select gnomon.review(:cr, 'approve');
select gnomon.merge('bot/1') as mb \gset
select t.eq((select price from products where id = 1), 11, 'the agent''s work merged');
select gnomon.agent_stop('bot', now() - interval '1 hour') as stopped \gset
select t.eq(jsonb_array_length((:'stopped'::jsonb) -> 'merges_undone'), 1, 'its merge undone');
select t.eq((select price from products where id = 1), 10, 'main restored');
select t.ok(not (select rolcanlogin from pg_roles where rolname = 'gnomon_agent_bot'), 'its login is disabled');
select t.eq((select status from gnomon.branch where name = 'bot/2'), 'closed', 'its open branch closed');
select t.eq((select count(*) from gnomon.agent_auth(:'bot_token')), 0::bigint, 'its token no longer works');
select t.ok(not exists (select 1 from gnomon.doctor() where check_name = 'assignment gnomon_agent_bot'), 'doctor does not warn about a stopped agent');
select t.ok(gnomon.explain_error('P0001', 'x [gnomon:some_code]') like '%https://gnomon.bitsinfra.com/errors%', 'an unknown code points at the errors page');

-------------------------------------------------------------------------------
-- expiry of logged branches
select gnomon.create_branch('old-work');
select gnomon.set_branch_ttl('old-work', '1 day');
update gnomon.branch set last_used = now() - interval '2 days' where name = 'old-work';
select t.eq((gnomon.expire_branches() ->> 'closed')::int, 1, 'an unused branch past its ttl is closed');
update gnomon.branch set expired_at = now() - interval '8 days' where name = 'old-work';
select t.eq((gnomon.expire_branches() ->> 'dropped')::int, 1, 'and dropped after the grace period');

-- merge window
select gnomon.create_branch('win');
select gnomon.use('win'); update products set price = 55 where id = 5; select gnomon.use('main');
select gnomon.set('merge_window', to_char(localtime + interval '1 hour', 'HH24:MI') || '-' || to_char(localtime + interval '2 hours', 'HH24:MI'));
select t.fails($$select gnomon.merge('win')$$, '55000', 'outside the merge window');
select gnomon.set('merge_window', '');
select gnomon.merge('win');

-- smaller pieces
select t.eq(gnomon.primary_key('gnomon_r_public.products'), array['id']::name[], 'primary key of a routing view');
select t.ok(gnomon.explain_error('42P10', 'there is no unique or exclusion constraint matching the ON CONFLICT specification') like '%C module%', 'explain an upsert');
select t.ok(gnomon.api_version() >= 2, 'api version');
select gnomon.create_branch('dk');
select gnomon.use('dk'); update products set price = price + 1; select gnomon.use('main');
select t.eq(jsonb_array_length(gnomon.diff_keys('dk', null, 'products', null, 2)), 2, 'a page of diff keys');
select t.eq((gnomon.diff_keys('dk', null, 'products', '{"id": 3}', 10)), '[{"id": 4}, {"id": 5}]'::jsonb, 'the next page');
select set_config('gnomon.branch', 'dk', false);
\if :cmod
-- with the C module the setting alone routes
select gnomon.assert_routed();
select t.ok((gnomon.status() ->> 'routed')::bool, 'the C module routes the setting alone');
\else
select t.fails($$select gnomon.assert_routed()$$, '55000', 'branch set but not routed');
select t.ok(gnomon.status() -> 'problems' ->> 0 like '%not_routed%', 'status names the problem');
\endif
select set_config('gnomon.branch', '', false);
select t.fails($$select gnomon.use('main', 'not a time')$$, null, 'a bad time fails when used, not at the first read');
select t.fails($$select gnomon.use('dkk')$$, '42704', 'unknown branch');

-- cleanup
select gnomon.unassign('gnomon_agent_bot'); select gnomon.unassign('gnomon_agent_spy');
select gnomon.unconfine('gnomon_agent_bot'); select gnomon.unconfine('gnomon_agent_spy'); select gnomon.unconfine('gt_runs');
drop owned by gnomon_agent_bot, gnomon_agent_spy, gt_app, gt_runs;
drop role gnomon_agent_bot; drop role gnomon_agent_spy; drop role gt_app; drop role gt_runs;
